  /* 拉当天历史事件，按"重要性"打分取前 limit 条 */
  function fetchZhHistory(limit) {
    limit = limit || 8;
    var d = new Date();
    var mm = String(d.getMonth() + 1).padStart(2, '0');
    var dd = String(d.getDate()).padStart(2, '0');
    var cacheKey = 'zhhist:' + mm + '-' + dd;

    // 先读 localStorage 缓存
    try {
      var cached = localStorage.getItem(cacheKey);
      if (cached) {
        var parsed = JSON.parse(cached);
        if (parsed && parsed.length) return Promise.resolve(parsed);
      }
    } catch (e) {}

    return fetch('https://api.wikimedia.org/feed/v1/wikipedia/zh/onthisday/all/' + mm + '/' + dd, {
      headers: { 'Api-User-Agent': 'BikoBlog/1.0 (https://biko-duckyo.pages.dev)' }
    })
      .then(function (r) { return r.json() })
      .then(function (json) {
        var events = (json && json.events) || [];
        // 打分：条目 extract 长度（重要性）+ pages 数量
        var scored = events.map(function (ev) {
          var pages = ev.pages || [];
          var extractLen = pages[0] && pages[0].extract ? pages[0].extract.length : 0;
          var score = extractLen + pages.length * 50;
          return {
            year: ev.year,
            text: t2s(ev.text || ''),
            link: pages[0] && pages[0].content_urls && pages[0].content_urls && pages[0].content_urls.desktop
              ? pages[0].content_urls.desktop.page : '',
            score: score
          };
        });
        scored.sort(function (a, b) { return b.score - a.score });
        var top = scored.slice(0, limit);
        try { localStorage.setItem(cacheKey, JSON.stringify(top)) } catch (e) {}
        return top;
      });
  }

  global.ZhHistory = { fetch: fetchZhHistory, t2s: t2s };
